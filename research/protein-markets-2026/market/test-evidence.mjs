import fs from 'node:fs';
import os from 'node:os';
import path from 'node:path';
import assert from 'node:assert/strict';
import crypto from 'node:crypto';
import {containedFile,verifyCapture,tradeObservations} from './build-evidence.mjs';
const dir=fs.mkdtempSync(path.join(os.tmpdir(),'sf-market-test-'));
const file=path.join(dir,'source');fs.writeFileSync(file,'original');
const row={id:'fixture',file:'source',bytes:8,sha256:crypto.createHash('sha256').update('original').digest('hex')};
assert.equal(verifyCapture(dir,row).file,fs.realpathSync(file));
fs.writeFileSync(file,'mutated!');assert.throws(()=>verifyCapture(dir,row),/Changed raw source/);
assert.throws(()=>containedFile(dir,'/etc/hosts'),/Invalid capture path/);
fs.symlinkSync('/etc/hosts',path.join(dir,'escape'));assert.throws(()=>containedFile(dir,'escape'),/escapes/);
const valid={typeCode:'C',freqCode:'A',classificationSearchCode:'HS',reporterCode:586,period:'2025',flowCode:'M',partnerCode:0,partner2Code:0,customsCode:'C00',motCode:0,cmdCode:'210610',primaryValue:10,netWgt:5,classificationCode:'H6',isReported:false,isAggregate:true,isNetWgtEstimated:false};
const raw=rows=>Buffer.from(JSON.stringify({count:rows.length,data:rows,error:''}));
const observations=tradeObservations(raw([valid]),row);assert.equal(observations[0].accepted_pillar_market_size,false);assert.equal(observations[0].is_reported,false);
assert.throws(()=>tradeObservations(raw([{...valid,reporterCode:356}]),row),/outside/);
assert.throws(()=>tradeObservations(raw([valid,valid]),row),/Duplicate/);
assert.throws(()=>tradeObservations(raw([{...valid,primaryValue:null}]),row),/Invalid trade value/);
assert.deepEqual(tradeObservations(raw([]),row),[]);
assert.throws(()=>tradeObservations(raw([{...valid,freqCode:'M'}]),row),/outside/);
assert.throws(()=>tradeObservations(raw([{...valid,classificationCode:'H5'}]),row),/outside/);
assert.throws(()=>tradeObservations(raw([{...valid,isReported:undefined}]),row),/provenance/);
console.log(JSON.stringify({status:'PASS',cases:12,limits:'Source identity, query boundaries and exclusion of upstream observations from pillar estimates; no market model tested'}));
